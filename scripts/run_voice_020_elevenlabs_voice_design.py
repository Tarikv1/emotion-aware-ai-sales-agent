def build_payload(cases_path: Path) -> dict[str, Any]:
    config = load_json(cases_path)
    available_sources = load_available_sources(config["source_artifacts"])
    return {
        "voice_milestone": VOICE_MILESTONE,
        "experiment_scope": config["experiment_scope"],
        "case_file": project_relative_string(cases_path),
        "source_artifacts": available_sources,
        "official_sources": config["official_sources"],
        "listening_feedback_basis": config["listening_feedback_basis"],
        "private_call_center_boundary": config["private_call_center_boundary"],
        "voice_design_ui_candidates": config["voice_design_ui_candidates"],
        "voice_remixing_prompts": config["voice_remixing_prompts"],
        "voice_design_profiles": config["voice_design_profiles"],
        "settings_matrix": config["settings_matrix"],
        "emotional_delivery_bundles": config["emotional_delivery_bundles"],
        "protected_text_rules": config["protected_text_rules"],
        "dashboard_steps": build_dashboard_steps(config),
        "summary": summarize(config, available_sources),
        "runtime_boundary": {
            "offline_design_only": True,
            "provider_calls_made": False,
            "requires_api_key": False,
            "customer_audio_uploaded": False,
            "private_audio_uploaded": False,
            "voice_cloning_used": False,
            "generated_audio_created": False,
            "quality_claim_allowed_without_human_rating": False,
            "provider_input_allowed_now": "synthetic voice-design prompts and synthetic preview text only",
        },
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build the VOICE-020 ElevenLabs voice design packet.")
    parser.add_argument("--cases", default=str(DEFAULT_CASES), help="VOICE-020 case/config file.")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="Path to write JSON output.")
    parser.add_argument("--report-out", default=str(DEFAULT_REPORT_OUT), help="Path to write Markdown report.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    cases_path = resolve_project_path(args.cases)
    out_path = resolve_project_path(args.out)
    report_path = resolve_project_path(args.report_out)
    if cases_path is None or out_path is None or report_path is None:
        raise SystemExit("Cases, output, and report paths are required.")

    payload = build_payload(cases_path)
    write_json(out_path, payload)
    write_text(report_path, render_report(payload))
    print(json.dumps(payload["summary"], indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
