#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
VOICE_MILESTONE = "VOICE-020"
DEFAULT_CASES = ROOT / "research" / "experiments" / "cases" / "voice-020-elevenlabs-voice-design.json"
DEFAULT_OUT = ROOT / "research" / "experiments" / "generated" / "VOICE-020-elevenlabs-voice-design.json"
DEFAULT_REPORT_OUT = ROOT / "research" / "experiments" / "generated" / "VOICE-020-elevenlabs-voice-design-report.md"


def resolve_project_path(path_text: str | None) -> Path | None:
    if not path_text:
        return None
    path = Path(path_text)
    if path.is_absolute():
        return path
    return ROOT / path


def project_relative_string(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def load_available_sources(source_artifacts: list[str]) -> list[dict[str, Any]]:
    available = []
    for source in source_artifacts:
        path = resolve_project_path(source)
        if path is None:
            continue
        available.append(
            {
                "path": project_relative_string(path),
                "exists": path.exists(),
                "used_as_private_data_source": False,
            }
        )
    return available


def summarize(config: dict[str, Any], available_sources: list[dict[str, Any]]) -> dict[str, Any]:
    languages = sorted({profile["language"] for profile in config["voice_design_profiles"]})
    return {
        "voice_design_profile_count": len(config["voice_design_profiles"]),
        "languages": languages,
        "voice_design_ui_candidate_count": len(config["voice_design_ui_candidates"]),
        "voice_remixing_prompt_count": len(config["voice_remixing_prompts"]),
        "settings_candidate_count": len(config["settings_matrix"]),
        "emotional_delivery_bundle_count": len(config["emotional_delivery_bundles"]),
        "protected_segment_type_count": len(config["protected_text_rules"]["segment_types"]),
        "official_source_count": len(config["official_sources"]),
        "source_artifacts_available": sum(1 for source in available_sources if source["exists"]),
        "provider_calls_made": False,
        "requires_api_key": False,
        "customer_audio_uploaded": False,
        "voice_cloning_used": False,
        "generated_audio_created": False,
        "quality_claim_allowed": False,
        "private_audio_uploaded": False,
        "private_audio_copied_to_generated_artifacts": False,
        "ready_for_elevenlabs_dashboard_voice_creation": True,
    }


def build_dashboard_steps(config: dict[str, Any]) -> list[str]:
    profile_ids = ", ".join(profile["profile_id"] for profile in config["voice_design_profiles"])
    ui_candidate_ids = ", ".join(candidate["candidate_id"] for candidate in config["voice_design_ui_candidates"])
    remix_prompt_ids = ", ".join(prompt["remix_prompt_id"] for prompt in config["voice_remixing_prompts"])
    candidate_ids = ", ".join(candidate["candidate_id"] for candidate in config["settings_matrix"])
    return [
        f"Create or select voice candidates for profiles: {profile_ids}.",
        "Use synthetic preview text only; do not upload private call audio or customer voices.",
        f"Try Voice Design UI candidates first: {ui_candidate_ids}.",
        f"Remix selected voices with prompts: {remix_prompt_ids}.",
        f"Test voice settings candidates: {candidate_ids}.",
        "Listen first to openings, then objection handling, then protected-text clarity.",
        "Keep human ratings separate from provider latency and response-content quality.",
        "Promote a voice only after English and German samples both pass the listening rubric.",
    ]


