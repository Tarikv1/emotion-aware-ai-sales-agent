        f"- NotebookLM API used: `{summary['notebooklm_api_used']}`",
        f"- External provider calls made: `{summary['external_provider_calls_made']}`",
        f"- Raw source text stored: `{summary['raw_source_text_stored']}`",
        f"- Customer/private data used: `{summary['customer_private_data_used']}`",
        f"- Validation passed: `{summary['validation_passed']}`",
        "",
        "## How To Use",
        "",
        "1. Open NotebookLM Configure Chat.",
        "2. Select Custom and paste `00-configure-chat-custom-instructions.md`.",
        "3. Set response length to Longer and save.",
        "4. Open the matching NotebookLM notebook/topic.",
        "5. Use the topic's `report_artifact` prompt in NotebookLM Reports / Create report.",
        "6. Export or copy the completed report file after NotebookLM creates it.",
        "7. Use `primary_report` only if a stricter JSON handoff is needed after the report exists.",
        "8. If it returns a small sample batch, partial status, or `NEED_CONTINUATION`, paste the topic's `gap_check` prompt.",
