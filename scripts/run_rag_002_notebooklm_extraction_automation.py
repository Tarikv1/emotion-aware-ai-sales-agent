        f"- Configure Chat character limit: `{summary['chat_customization_char_limit']}`",
        f"- Configure Chat within limit: `{summary['chat_customization_within_limit']}`",
        f"- Report artifact workflow enabled: `{summary['report_artifact_workflow_enabled']}`",
        f"- Primary prompts include readable report: `{summary['primary_prompts_include_readable_report']}`",
        f"- Primary prompts include JSON block: `{summary['primary_prompts_include_json_block']}`",
        f"- All prompts within limit: `{summary['all_prompts_within_limit']}`",
