#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from rag_knowledge_base import build_source_manifest_template
from rag_notebooklm_automation import (
    DEFAULT_CHAT_CUSTOMIZATION_CHAR_LIMIT,
    DEFAULT_MIN_CHUNKS_PER_TOPIC,
    DEFAULT_PROMPT_CHAR_LIMIT,
    RAG_AUTOMATION_ID,
    build_notebooklm_prompt_pack,
    validate_extraction_output,
    validate_prompt_pack,
)


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CASE = ROOT / "research" / "experiments" / "cases" / "rag-002-notebooklm-extraction-automation-bridge.json"
DEFAULT_OUTPUT_DIR = ROOT / "research" / "experiments" / "generated" / "RAG-002-notebooklm-extraction-automation-bridge"
DEFAULT_RESULT = DEFAULT_OUTPUT_DIR / "result.json"
DEFAULT_REPORT = DEFAULT_OUTPUT_DIR / "report.md"
DEFAULT_PROMPT_DIR = DEFAULT_OUTPUT_DIR / "prompts"
DEFAULT_IMPORT_DIR = DEFAULT_OUTPUT_DIR / "imports"


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip()).strip("-").lower()
    return slug or "topic"


def load_case(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def write_prompt_files(prompt_pack: dict[str, Any], prompt_dir: Path) -> list[dict[str, str]]:
    written: list[dict[str, str]] = []
    prompt_dir.mkdir(parents=True, exist_ok=True)
    chat_customization = prompt_pack.get("chat_customization") or {}
    chat_path = prompt_dir / "00-configure-chat-custom-instructions.md"
    chat_path.write_text(str(chat_customization.get("text", "")), encoding="utf-8")
    written.append(
        {
            "topic_id": "configure_chat",
            "prompt_type": "custom_instructions",
            "path": str(chat_path.relative_to(ROOT)).replace("\\", "/"),
            "char_count": str(chat_customization.get("char_count", 0)),
        }
    )
    for index, topic in enumerate(prompt_pack.get("topics", []), start=1):
        topic_slug = f"{index:02d}-{slugify(topic['topic_id'])}"
        topic_dir = prompt_dir / topic_slug
        topic_dir.mkdir(parents=True, exist_ok=True)
        prompt_file_names = {
            "report_artifact": "01-create-report-file.md",
            "primary_report": "02-chat-json-extraction.md",
            "gap_check": "03-gap-check.md",
        }
        for prompt_type in ("report_artifact", "primary_report", "gap_check"):
            prompt = topic["prompts"][prompt_type]
            filename = prompt_file_names[prompt_type]
            path = topic_dir / filename
            path.write_text(prompt["text"], encoding="utf-8")
            written.append(
                {
                    "topic_id": topic["topic_id"],
                    "prompt_type": prompt_type,
                    "path": str(path.relative_to(ROOT)).replace("\\", "/"),
                    "char_count": str(prompt["char_count"]),
                }
            )
    index_lines = [
        "# RAG-002 NotebookLM Prompt Index",
        "",
        "First paste `00-configure-chat-custom-instructions.md` into NotebookLM Configure Chat > Custom, and set response length to Longer.",
        "",
        "Then use each topic's `01-create-report-file.md` inside NotebookLM Reports / Create report. Use `02-chat-json-extraction.md` only if you need a stricter JSON handoff after the report exists.",
        "",
    ]
    for item in written:
        index_lines.append(f"- `{item['topic_id']}` `{item['prompt_type']}` `{item['char_count']} chars`: `{item['path']}`")
    (prompt_dir / "PROMPT_INDEX.md").write_text("\n".join(index_lines) + "\n", encoding="utf-8")
    return written


def write_import_readme(import_dir: Path) -> None:
    import_dir.mkdir(parents=True, exist_ok=True)
    lines = [
        "# RAG-002 NotebookLM Import Drop Zone",
        "",
        "Paste or export NotebookLM JSON outputs here later, one file per topic.",
        "",
        "Rules:",
        "",
        "- keep raw source text, full transcripts, book chapters, private data, and API keys out of this folder",
        "- import only NotebookLM outputs that include `completion_status`, `coverage_checklist`, and `chunks`",
        "- outputs without `END: COMPLETE` are treated as partial and should be gap-checked before promotion",
        "- small sample batches should not be promoted into the local RAG base",
        "",
    ]
    (import_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


